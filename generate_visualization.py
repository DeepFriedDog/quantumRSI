#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""
Generate visualizations from strategy backtest summary CSV files.

This script takes a CSV file generated by a backtesting script
(like comprehensive_quantum_strategy_backtest.py) and creates a
multi-panel visualization comparing strategy performance.
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
import seaborn as sns
import argparse
import os
from pathlib import Path
import matplotlib.ticker as mticker
import re # Import regex

# --- Configuration: Define Base Strategy Names and Groups ---
BASE_STRATEGY_NAMES = [
    "Quantum Stock - Balanced",
    "Quantum Stock - Aggressive",
    "Quantum Stock Hybrid",
    "Quantum Oscillator - Classic",
    "Quantum Hybrid Enhanced"
    # Add any other base strategy names if they appear
]

STRATEGY_GROUPS = {
    "Stock": ["Quantum Stock - Balanced", "Quantum Stock - Aggressive"],
    "Hybrid": ["Quantum Stock Hybrid", "Quantum Hybrid Enhanced"],
    "Oscillator": ["Quantum Oscillator - Classic"],
    "All": BASE_STRATEGY_NAMES # Special group for overall plot
}
# --- End Configuration ---

def extract_base_strategy_name(strategy_col):
    """Extract the base part of the strategy name."""
    # Attempt to remove token_timeframe suffix if present
    # Assumes suffix pattern like _TOKEN/PAIR_TIMEFRAME
    # More robust: Check against known base names
    for base_name in BASE_STRATEGY_NAMES:
        if strategy_col.startswith(base_name):
            # Check if there's a suffix to remove (prevent removing parts of base names)
            if len(strategy_col) > len(base_name) and strategy_col[len(base_name)] == '_':
                 return base_name
            elif len(strategy_col) == len(base_name):
                 return base_name # Exact match
    # Fallback if no base name matches (shouldn't happen with config)
    print(f"Warning: Could not extract base name for '{strategy_col}', using original.")
    return strategy_col


def load_data(csv_filepath):
    """Load the summary data from the CSV file."""
    if not os.path.exists(csv_filepath):
        print(f"Error: CSV file not found at {csv_filepath}")
        return None
    try:
        df = pd.read_csv(csv_filepath)
        print(f"Loaded data from {csv_filepath}")
        # --- Clean Strategy Names ---
        if 'Strategy' in df.columns:
             df['BaseStrategy'] = df['Strategy'].apply(extract_base_strategy_name)
        else:
            print("Error: 'Strategy' column not found in CSV.")
            return None
        # --- End Clean Strategy Names ---

        # Basic validation
        required_columns = ['BaseStrategy', 'Timeframe', 'Return [%]', 'Win Rate [%]', 'Total Trades', 'Max Drawdown [%]', 'Profit Factor', 'Risk/Reward']
        if not all(col in df.columns for col in required_columns):
            print(f"Error: CSV missing required columns (after adding BaseStrategy). Need: {required_columns}. Found: {df.columns.tolist()}")
            return None
        # Convert relevant columns to numeric, coercing errors
        numeric_cols = ['Return [%]', 'Win Rate [%]', 'Total Trades', 'Max Drawdown [%]', 'Profit Factor', 'Risk/Reward']
        for col in numeric_cols:
             if col in df.columns:
                 df[col] = pd.to_numeric(df[col], errors='coerce')
        # Drop rows where essential numeric conversion failed or where Total Trades is zero
        initial_rows = len(df)
        df.dropna(subset=numeric_cols, inplace=True)
        df = df[df['Total Trades'] > 0] # Exclude rows with zero trades
        rows_dropped = initial_rows - len(df)
        if rows_dropped > 0:
             print(f"Dropped {rows_dropped} rows due to NaN values in numeric columns or zero trades.")

        print(f"Data shape after loading and cleaning: {df.shape}")
        return df
    except Exception as e:
        print(f"Error loading or processing CSV file: {e}")
        return None


def create_visualizations(summary_df, output_filename_base, group_name="All Strategies"):
    """Create comprehensive visualizations comparing strategies in the provided DataFrame."""
    if summary_df is None or summary_df.empty:
        print(f"Error: No data available for visualization group: {group_name}")
        return

    print(f"Creating visualizations for group: {group_name}...")

    # Define Timeframe order for consistent plotting
    timeframe_order = ['1m', '5m', '15m', '30m', '1h', '4h', '1d']
    # Filter summary_df to only include timeframes in the desired order
    # Use BaseStrategy now for grouping and display
    plot_df = summary_df[summary_df['Timeframe'].isin(timeframe_order)].copy()
    if plot_df.empty:
        print(f"Error: No data found for the specified timeframes in group: {group_name}")
        return
    plot_df['Timeframe'] = pd.Categorical(plot_df['Timeframe'], categories=timeframe_order, ordered=True)

    # Create a multi-panel figure (4 rows, 2 columns)
    plt.style.use('seaborn-v0_8-darkgrid') # Use a seaborn style
    fig = plt.figure(figsize=(18, 22))
    gs = gridspec.GridSpec(4, 2, height_ratios=[1, 1, 1.2, 1], width_ratios=[1,1], hspace=0.4, wspace=0.3)

    # Use the group name in the title
    fig.suptitle(f"Performance Analysis - {group_name} ({Path(output_filename_base).stem})", fontsize=18, y=0.99)

    # --- Top Row: Heatmaps --- #
    # Use 'BaseStrategy' for index
    ax1 = plt.subplot(gs[0, 0])
    try:
        win_rate_pivot = plot_df.pivot_table(
            values='Win Rate [%]',
            index='BaseStrategy', # Use BaseStrategy
            columns='Timeframe',
            aggfunc='mean'
        )
        if not win_rate_pivot.empty:
            win_rate_pivot = win_rate_pivot.reindex(columns=timeframe_order)
            sns.heatmap(win_rate_pivot, annot=True, cmap='RdYlGn', fmt='.1f', ax=ax1, linewidths=.5, cbar_kws={'label': 'Avg Win Rate (%)'})
            ax1.set_title('Average Win Rate (%) by Strategy and Timeframe', fontsize=13)
            ax1.set_xlabel('Timeframe')
            ax1.set_ylabel('Strategy') # Keep Strategy label
            plt.setp(ax1.yaxis.get_majorticklabels(), rotation=0)
        else:
            ax1.text(0.5, 0.5, 'No data for Win Rate heatmap', ha='center', va='center', wrap=True)
            ax1.set_title('Average Win Rate (%) by Strategy and Timeframe', fontsize=13)
    except Exception as e:
        print(f"Error plotting Win Rate Heatmap for {group_name}: {e}")
        ax1.text(0.5, 0.5, f'Error plotting Win Rate Heatmap:\n{e}', ha='center', va='center', wrap=True)
        ax1.set_title('Average Win Rate (%) by Strategy and Timeframe', fontsize=13)

    ax2 = plt.subplot(gs[0, 1])
    try:
        return_pivot = plot_df.pivot_table(
            values='Return [%]',
            index='BaseStrategy', # Use BaseStrategy
            columns='Timeframe',
            aggfunc='mean'
        )
        if not return_pivot.empty:
            return_pivot = return_pivot.reindex(columns=timeframe_order)
            sns.heatmap(return_pivot, annot=True, cmap='RdYlGn', fmt='.1f', ax=ax2, linewidths=.5, center=0, cbar_kws={'label': 'Avg Return (%)'})
            ax2.set_title('Average Return (%) by Strategy and Timeframe', fontsize=13)
            ax2.set_xlabel('Timeframe')
            ax2.set_ylabel('')
            ax2.set_yticks([])
        else:
            ax2.text(0.5, 0.5, 'No data for Return heatmap', ha='center', va='center', wrap=True)
            ax2.set_title('Average Return (%) by Strategy and Timeframe', fontsize=13)
    except Exception as e:
        print(f"Error plotting Return Heatmap for {group_name}: {e}")
        ax2.text(0.5, 0.5, f'Error plotting Return Heatmap:\n{e}', ha='center', va='center', wrap=True)
        ax2.set_title('Average Return (%) by Strategy and Timeframe', fontsize=13)

    # --- Second Row: Box Plots --- #
    # Use 'BaseStrategy' for x-axis and grouping
    ax3 = plt.subplot(gs[1, 0])
    try:
        if not plot_df.empty:
            sorted_strategies_return = plot_df.groupby('BaseStrategy')['Return [%]'].median().sort_values().index
            sns.boxplot(x='BaseStrategy', y='Return [%]', data=plot_df, ax=ax3, order=sorted_strategies_return, palette='viridis', showfliers=True)
            ax3.set_xticklabels(ax3.get_xticklabels(), rotation=45, ha='right')
            ax3.set_title('Distribution of Returns (%) by Strategy', fontsize=13)
            ax3.set_xlabel('Strategy') # Keep Strategy label
            ax3.set_ylabel('Return (%)\n(Each point=1 Token/Timeframe Test)')
        else:
             ax3.text(0.5, 0.5, 'No data for Return Boxplot', ha='center', va='center', wrap=True)
             ax3.set_title('Distribution of Returns (%) by Strategy', fontsize=13)
    except Exception as e:
        print(f"Error plotting Return Boxplot for {group_name}: {e}")
        ax3.text(0.5, 0.5, f'Error plotting Return Boxplot:\n{e}', ha='center', va='center', wrap=True)
        ax3.set_title('Distribution of Returns (%) by Strategy', fontsize=13)

    ax4 = plt.subplot(gs[1, 1])
    try:
        if not plot_df.empty:
            sorted_strategies_winrate = plot_df.groupby('BaseStrategy')['Win Rate [%]'].median().sort_values().index
            sns.boxplot(x='BaseStrategy', y='Win Rate [%]', data=plot_df, ax=ax4, order=sorted_strategies_winrate, palette='viridis', showfliers=True)
            ax4.set_xticklabels(ax4.get_xticklabels(), rotation=45, ha='right')
            ax4.set_title('Distribution of Win Rates (%) by Strategy', fontsize=13)
            ax4.set_xlabel('Strategy') # Keep Strategy label
            ax4.set_ylabel('Win Rate (%)\n(Each point=1 Token/Timeframe Test)')
        else:
            ax4.text(0.5, 0.5, 'No data for Win Rate Boxplot', ha='center', va='center', wrap=True)
            ax4.set_title('Distribution of Win Rates (%) by Strategy', fontsize=13)
    except Exception as e:
        print(f"Error plotting Win Rate Boxplot for {group_name}: {e}")
        ax4.text(0.5, 0.5, f'Error plotting Win Rate Boxplot:\n{e}', ha='center', va='center', wrap=True)
        ax4.set_title('Distribution of Win Rates (%) by Strategy', fontsize=13)

    # --- Third Row: Scatter and Bar --- #
    # Use 'BaseStrategy' for hue and grouping
    ax5 = plt.subplot(gs[2, 0])
    try:
        if not plot_df.empty:
            scatter_plot = sns.scatterplot(
                x='Win Rate [%]',
                y='Return [%]',
                hue='BaseStrategy', # Use BaseStrategy
                size='Total Trades',
                sizes=(30, 180),
                alpha=0.7,
                data=plot_df,
                ax=ax5,
                palette='tab10'
            )
            ax5.set_title('Win Rate vs Return (size = # of trades)', fontsize=13)
            ax5.set_xlabel('Win Rate (%)')
            ax5.set_ylabel('Return (%)')
            ax5.axhline(0, color='grey', linestyle='--', linewidth=0.8)
            ax5.axvline(50, color='grey', linestyle='--', linewidth=0.8)
            ax5.legend(bbox_to_anchor=(1.05, 1), loc='upper left', borderaxespad=0., fontsize=9, title='Strategy & # Trades')
        else:
            ax5.text(0.5, 0.5, 'No data for Scatter Plot', ha='center', va='center', wrap=True)
            ax5.set_title('Win Rate vs Return (size = # of trades)', fontsize=13)
    except Exception as e:
        print(f"Error plotting Scatter Plot for {group_name}: {e}")
        ax5.text(0.5, 0.5, f'Error plotting Scatter Plot:\n{e}', ha='center', va='center', wrap=True)
        ax5.set_title('Win Rate vs Return (size = # of trades)', fontsize=13)

    ax6 = plt.subplot(gs[2, 1])
    try:
        if not plot_df.empty:
            plot_df['Risk/Reward_Clean'] = plot_df['Risk/Reward'].replace([np.inf, -np.inf], np.nan)
            # Handle cases where all Risk/Reward values for a group might be NaN
            risk_adj_pivot = plot_df.groupby('BaseStrategy')['Risk/Reward_Clean'].mean()
            risk_adj_pivot = risk_adj_pivot.dropna().sort_values(ascending=False) # Drop NaN means before sorting

            if not risk_adj_pivot.empty:
                 sns.barplot(
                     x=risk_adj_pivot.index,
                     y=risk_adj_pivot.values,
                     ax=ax6,
                     palette='coolwarm'
                 )
                 ax6.set_xticklabels(ax6.get_xticklabels(), rotation=45, ha='right')
                 ax6.set_title('Average Risk-Adjusted Return (Return/Drawdown)', fontsize=13)
                 ax6.set_xlabel('Strategy') # Keep Strategy label
                 ax6.set_ylabel('Avg Return / Max Drawdown Ratio')
                 ax6.axhline(0, color='black', linewidth=0.8)
            else:
                 ax6.text(0.5, 0.5, 'No valid Risk/Reward data for this group', ha='center', va='center', wrap=True)
                 ax6.set_title('Average Risk-Adjusted Return (Return/Drawdown)', fontsize=13)
        else:
            ax6.text(0.5, 0.5, 'No data for Risk/Reward Chart', ha='center', va='center', wrap=True)
            ax6.set_title('Average Risk-Adjusted Return (Return/Drawdown)', fontsize=13)

    except Exception as e:
        print(f"Error plotting Risk/Reward Bar Chart for {group_name}: {e}")
        ax6.text(0.5, 0.5, f'Error plotting Risk/Reward Bar Chart:\n{e}', ha='center', va='center', wrap=True)
        ax6.set_title('Average Risk-Adjusted Return (Return/Drawdown)', fontsize=13)

    # --- Bottom Row: Strategy Performance Summary Table (Updated Format) --- #
    ax7 = plt.subplot(gs[3, :])
    ax7.axis('off') # Hide axes for table
    try:
        if not plot_df.empty:
            # Calculate overall metrics by strategy (use BaseStrategy)
            strategy_summary = plot_df.groupby('BaseStrategy').agg(
                AvgWinRate=('Win Rate [%]', 'mean'),
                AvgReturn=('Return [%]', 'mean'),
                AvgMaxDD=('Max Drawdown [%]', 'mean'),
                AvgProfitFactor=('Profit Factor', lambda x: x.replace([np.inf, -np.inf], np.nan).mean()),
                AvgRiskReward=('Risk/Reward_Clean', 'mean'), # Use cleaned version
                TotalTrades=('Total Trades', 'sum')
            # Sort by index (strategy name) for consistent order if needed, or keep Return sort
            ).sort_values('AvgReturn', ascending=False)

            # Calculate count of profitable tests per BaseStrategy
            profitable_tests = plot_df[plot_df['Return [%]'] > 0].groupby('BaseStrategy').size()
            total_tests = plot_df.groupby('BaseStrategy').size()

            # Add profitable test info to summary, handling strategies with 0 tests
            strategy_summary['ProfitableTests'] = profitable_tests.reindex(strategy_summary.index).fillna(0).astype(int)
            strategy_summary['TotalTests'] = total_tests.reindex(strategy_summary.index).fillna(0).astype(int)
            # Calculate percentage safely (avoid division by zero)
            strategy_summary['ProfitablePct'] = np.where(
                strategy_summary['TotalTests'] > 0,
                (strategy_summary['ProfitableTests'] / strategy_summary['TotalTests'] * 100),
                0
            ).fillna(0)

            if not strategy_summary.empty:
                # Format the table data according to the desired format
                table_data = []
                for idx, row in strategy_summary.iterrows():
                    table_data.append([
                        idx, # Strategy Name (Base)
                        f"{row['AvgWinRate']:.1f}%" if pd.notna(row['AvgWinRate']) else 'N/A',
                        f"{row['AvgReturn']:.1f}%" if pd.notna(row['AvgReturn']) else 'N/A',
                        f"{row['AvgMaxDD']:.1f}%" if pd.notna(row['AvgMaxDD']) else 'N/A',
                        f"{row['AvgProfitFactor']:.2f}" if pd.notna(row['AvgProfitFactor']) else 'N/A',
                        f"{row['AvgRiskReward']:.2f}" if pd.notna(row['AvgRiskReward']) else 'N/A',
                        f"{row['ProfitableTests']}/{row['TotalTests']} ({row['ProfitablePct']:.1f}%)",
                        f"{int(row['TotalTrades'])}" if pd.notna(row['TotalTrades']) else 'N/A'
                    ])

                # Define headers matching the example image
                header = ['Strategy', 'Avg Win Rate', 'Avg Return', 'Avg Max DD', 'Profit Factor', 'Risk/Reward', 'Profitable Tests', 'Total Trades']

                # Create the table
                table = ax7.table(
                    cellText=table_data,
                    colLabels=header,
                    cellLoc='center',
                    loc='center',
                    colWidths=[0.22, 0.11, 0.11, 0.11, 0.11, 0.11, 0.14, 0.09] # Adjusted widths
                )

                # Style the table
                table.auto_set_font_size(False)
                table.set_fontsize(9)
                table.scale(1, 1.6)

                # Optional Color Coding
                for i, idx in enumerate(strategy_summary.index):
                     return_val = strategy_summary.loc[idx, 'AvgReturn']
                     if pd.isna(return_val): cell_color = 'lightgrey'
                     elif return_val > 5: cell_color = '#90EE90'
                     elif return_val >= 0: cell_color = '#FFFFE0'
                     elif return_val > -10: cell_color = '#FFB6C1'
                     else: cell_color = '#F08080'
                     for j in range(len(header)):
                         table[(i + 1, j)].set_facecolor(cell_color)
                # Style header
                for j in range(len(header)):
                    table[(0, j)].set_facecolor('#DDDDDD') # Light grey header
                    table[(0, j)].set_text_props(weight='bold')

                ax7.set_title('Strategy Performance Summary', fontsize=14, y=0.95) # Adjust title position
            else:
                ax7.text(0.5, 0.5, 'No summary data to display for this group', ha='center', va='center', wrap=True)
                ax7.set_title('Strategy Performance Summary', fontsize=14)
        else:
            ax7.text(0.5, 0.5, 'No data available for Summary Table', ha='center', va='center', wrap=True)
            ax7.set_title('Strategy Performance Summary', fontsize=14)

    except Exception as e:
        print(f"Error creating summary table for {group_name}: {e}")
        ax7.text(0.5, 0.5, f'Error creating summary table:\n{e}', ha='center', va='center', wrap=True)
        ax7.set_title('Strategy Performance Summary', fontsize=14)

    # Save the figure
    output_filepath = f"{output_filename_base}_{group_name.lower().replace(' ', '_')}.png"
    try:
        plt.savefig(output_filepath, bbox_inches='tight', dpi=150)
        print(f"Visualization saved to {output_filepath}")
    except Exception as e:
        print(f"Error saving visualization {output_filepath}: {e}")
    plt.close(fig) # Close the figure to free memory

def main():
    parser = argparse.ArgumentParser(description="Generate visualizations from strategy backtest summary CSV.")
    parser.add_argument("csv_filepath", help="Path to the input summary CSV file.")
    parser.add_argument("-o", "--output", help="Base name for the output PNG file(s). Defaults to CSV name.")
    args = parser.parse_args()

    # Determine output base name
    if args.output:
        output_base = args.output
    else:
        output_base = Path(args.csv_filepath).stem

    # Ensure output directory exists (use directory of CSV file)
    output_dir = Path(args.csv_filepath).parent
    os.makedirs(output_dir, exist_ok=True)
    output_path_base = os.path.join(output_dir, output_base)

    # Load the full dataset
    full_summary_df = load_data(args.csv_filepath)

    if full_summary_df is None:
        print("Exiting due to data loading errors.")
        return

    # Generate plots for each defined group
    for group_name, strategy_list in STRATEGY_GROUPS.items():
        # Filter the DataFrame for the current group
        # Use .isin() for exact matches with the base strategy names
        group_df = full_summary_df[full_summary_df['BaseStrategy'].isin(strategy_list)].copy()

        if group_df.empty:
            print(f"Skipping group '{group_name}': No data found for strategies {strategy_list}")
            continue

        # Generate the visualization for this group
        create_visualizations(group_df, output_path_base, group_name)

if __name__ == "__main__":
    main()
